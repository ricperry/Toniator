#[derive(Debug, Clone, Copy)]
pub(crate) struct MarkSvgPresentation<'a> {
    pub title: &'a str,
    pub artboard_width: u32,
    pub artboard_height: u32,
    pub output_model: OutputModel,
    pub export_background: ExportBackground,
}

pub fn export_svg(path: &Path, document: &Document) -> Result<()> {
    export_svg_cancellable(path, document, &CancellationToken::new())
}

pub fn export_svg_cancellable(
    path: &Path,
    document: &Document,
    token: &CancellationToken,
) -> Result<()> {
    token.checkpoint()?;
    let mut canonical = document.clone();
    let source_size = source_dimensions(&canonical.source)?;
    canonical.normalize_canvas_aspect(source_size.0, source_size.1);
    canonical.canonicalize_pipeline_facades()?;
    let document = &canonical;
    document.validate()?;
    let output = generate_document_pattern_output_cancellable(document, token)?;
    match &output {
        CanonicalPatternOutput::Marks(output) => {
            export_mark_svg(path, document, &output.geometry, token)
        }
        CanonicalPatternOutput::Paths(output) => {
            export_curve_svg(path, document, &output.geometry, token)
        }
        CanonicalPatternOutput::Regions(_)
        | CanonicalPatternOutput::Network(_)
        | CanonicalPatternOutput::Composite(_) => {
            let bytes = canonical_pattern_svg_bytes_with_background_cancellable(
                &output,
                &document.source.name,
                document.appearance.export_background,
                token,
            )?;
            atomic_write_cancellable(path, &bytes, token)
        }
    }
}

fn export_mark_svg(
    path: &Path,
    document: &Document,
    mark_set: &MarkSet,
    token: &CancellationToken,
) -> Result<()> {
    let bytes = mark_svg_bytes_cancellable(
        mark_set,
        mark_svg_presentation_for_document(document)?,
        token,
    )?;
    atomic_write_cancellable(path, &bytes, token)
}

pub(crate) fn mark_svg_presentation_for_document(
    document: &Document,
) -> Result<MarkSvgPresentation<'_>> {
    let (artboard_width, artboard_height) = match &document.render {
        RenderVariant::NativeBasicV1 => source_dimensions(&document.source)?,
        RenderVariant::WebShapeV1 { settings } => (settings.output_width, settings.output_height),
        RenderVariant::WebCurveV1 { settings } => (settings.output_width, settings.output_height),
        RenderVariant::WeightedVoronoiCanonicalV1 => source_dimensions(&document.source)?,
    };
    Ok(MarkSvgPresentation {
        title: &document.source.name,
        artboard_width,
        artboard_height,
        output_model: document.artwork_pipeline.output_model,
        export_background: document.appearance.export_background,
    })
}

/// Serializes already-generated canonical Shapes marks without consulting the
/// renderer or document pattern state. The file exporter writes these exact
/// bytes through its established atomic path.
pub(crate) fn mark_svg_bytes_cancellable(
    mark_set: &MarkSet,
    presentation: MarkSvgPresentation<'_>,
    token: &CancellationToken,
) -> Result<Vec<u8>> {
    token.checkpoint()?;
    let scale_x = presentation.artboard_width as f32 / mark_set.width as f32;
    let scale_y = presentation.artboard_height as f32 / mark_set.height as f32;
    let mut svg = String::with_capacity(mark_set.marks.len() * 110);
    writeln!(
        svg,
        r#"<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" width="{}" height="{}" viewBox="0 0 {} {}" style="isolation:isolate">"#,
        presentation.artboard_width,
        presentation.artboard_height,
        presentation.artboard_width,
        presentation.artboard_height
    )?;
    writeln!(
        svg,
        "  <title>Toniator — {}</title>",
        xml_escape(presentation.title)
    )?;
    writeln!(
        svg,
        "  <desc>Editable {} halftone generated by Toniator</desc>",
        if presentation.output_model == OutputModel::RgbScreen {
            "RGB screen"
        } else {
            "CMYK ink"
        }
    )?;
    write_export_background(&mut svg, presentation.export_background)?;

    for layer in mark_set.layers.iter().filter(|layer| layer.enabled) {
        token.checkpoint()?;
        let channel = layer.channel;
        let (r, g, b) = layer.color;
        let label = match layer.channel {
            Channel::Cyan => "Cyan",
            Channel::Magenta => "Magenta",
            Channel::Yellow => "Yellow",
            Channel::Black => "Black",
            Channel::Red => "Red",
            Channel::Green => "Green",
            Channel::Blue => "Blue",
        };
        writeln!(
            svg,
            "  <g id=\"toniator-{}\" inkscape:groupmode=\"layer\" inkscape:label=\"{}\" fill=\"#{:02x}{:02x}{:02x}\" opacity=\"{}\" style=\"mix-blend-mode:{}\">",
            channel.id(),
            label,
            r,
            g,
            b,
            number(layer.opacity),
            if presentation.output_model == OutputModel::RgbScreen {
                "screen"
            } else {
                "multiply"
            }
        )?;
        for (index, mark) in mark_set
            .marks
            .iter()
            .filter(|mark| mark.channel == channel)
            .enumerate()
        {
            if index % 512 == 0 {
                token.checkpoint()?;
            }
            write_mark(&mut svg, scale_mark(mark.clone(), scale_x, scale_y), index)?;
        }
        writeln!(svg, "  </g>")?;
    }
    writeln!(svg, "</svg>")?;
    token.checkpoint()?;
    Ok(svg.into_bytes())
}

#[derive(Debug, Clone, Copy)]
pub(crate) struct CurveSvgPresentation<'a> {
    pub title: &'a str,
    pub output_model: OutputModel,
    pub export_background: ExportBackground,
    pub crosshatch_compatibility: bool,
}

pub(crate) fn curve_svg_presentation_for_document(document: &Document) -> CurveSvgPresentation<'_> {
    CurveSvgPresentation {
        title: &document.source.name,
        output_model: document.artwork_pipeline.output_model,
        export_background: document.appearance.export_background,
        crosshatch_compatibility: matches!(
            document.artwork_pipeline.assignment,
            ChannelAssignment::LegacyCompatibility(
                LegacyCompatibilityAssignment::CrosshatchProgressiveKcmyV1
            )
        ),
    }
}

/// Serializes already-generated canonical Curves paths without consulting the
/// renderer or document pattern state. The file exporter writes these exact
/// bytes through its established atomic path.
pub(crate) fn curve_svg_bytes_cancellable(
    geometry: &crate::curve_render::CurveGeometry,
    presentation: CurveSvgPresentation<'_>,
    token: &CancellationToken,
) -> Result<Vec<u8>> {
    token.checkpoint()?;
    let mut svg = String::new();
    writeln!(
        svg,
        r#"<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" width="{}" height="{}" viewBox="0 0 {} {}" style="isolation:isolate">"#,
        geometry.width, geometry.height, geometry.width, geometry.height
    )?;
    writeln!(
        svg,
        "  <title>Toniator — {}</title>",
        xml_escape(presentation.title)
    )?;
    writeln!(
        svg,
        "  <desc>Editable {} full-width curve halftone generated by Toniator</desc>",
        if presentation.output_model == OutputModel::RgbScreen {
            "RGB screen"
        } else {
            "CMYK ink"
        }
    )?;
    writeln!(
        svg,
        "  <defs><clipPath id=\"toniator-artboard-clip\"><rect x=\"0\" y=\"0\" width=\"{}\" height=\"{}\"/></clipPath></defs>",
        geometry.width, geometry.height
    )?;
    write_export_background(&mut svg, presentation.export_background)?;
    for layer in &geometry.layers {
        token.checkpoint()?;
        let channel = layer.layer.channel;
        let (r, g, b) = layer.layer.color;
        let label = if presentation.crosshatch_compatibility {
            match channel {
                Channel::Black => "Layer 1 (K)",
                Channel::Cyan => "Layer 2 (C)",
                Channel::Magenta => "Layer 3 (M)",
                Channel::Yellow => "Layer 4 (Y)",
                Channel::Red => "Red",
                Channel::Green => "Green",
                Channel::Blue => "Blue",
            }
        } else {
            match channel {
                Channel::Cyan => "Cyan",
                Channel::Magenta => "Magenta",
                Channel::Yellow => "Yellow",
                Channel::Black => "Black",
                Channel::Red => "Red",
                Channel::Green => "Green",
                Channel::Blue => "Blue",
            }
        };
        writeln!(
            svg,
            "  <g id=\"toniator-{}\" inkscape:groupmode=\"layer\" inkscape:label=\"{}\" fill=\"#{:02x}{:02x}{:02x}\" opacity=\"{}\" style=\"mix-blend-mode:{}\" clip-path=\"url(#toniator-artboard-clip)\">",
            channel.id(),
            label,
            r,
            g,
            b,
            number(layer.layer.opacity),
            if !presentation.crosshatch_compatibility
                && presentation.output_model == OutputModel::RgbScreen
            {
                "screen"
            } else {
                "multiply"
            }
        )?;
        for (index, outline) in layer.outlines.iter().enumerate() {
            if index % 512 == 0 {
                token.checkpoint()?;
            }
            writeln!(
                svg,
                "    <path id=\"{}-curve-{}\" d=\"{}\" fill-rule=\"nonzero\"/>",
                channel.id(),
                index,
                outline.to_svg_path_data()
            )?;
        }
        writeln!(svg, "  </g>")?;
    }
    writeln!(svg, "</svg>")?;
    token.checkpoint()?;
    Ok(svg.into_bytes())
}

fn export_curve_svg(
    path: &Path,
    document: &Document,
    geometry: &crate::curve_render::CurveGeometry,
    token: &CancellationToken,
) -> Result<()> {
    let bytes = curve_svg_bytes_cancellable(
        geometry,
        curve_svg_presentation_for_document(document),
        token,
    )?;
    atomic_write_cancellable(path, &bytes, token)
}

/// Serializes synthetic Stage 3 region/network fixtures as an editable SVG.
/// The artboard clip is explicit and subtractive geometry is emitted through
/// SVG masks, never as a background-coloured stroke.
pub fn canonical_pattern_svg_bytes(
    output: &CanonicalPatternOutput,
    title: &str,
) -> Result<Vec<u8>> {
    canonical_pattern_svg_bytes_with_background_cancellable(
        output,
        title,
        ExportBackground::None,
        &CancellationToken::new(),
    )
}

pub fn canonical_pattern_svg_bytes_cancellable(
    output: &CanonicalPatternOutput,
    title: &str,
    token: &CancellationToken,
) -> Result<Vec<u8>> {
    canonical_pattern_svg_bytes_with_background_cancellable(
        output,
        title,
        ExportBackground::None,
        token,
    )
}

fn canonical_pattern_svg_bytes_with_background_cancellable(
    output: &CanonicalPatternOutput,
    title: &str,
    export_background: ExportBackground,
    token: &CancellationToken,
) -> Result<Vec<u8>> {
    token.checkpoint()?;
    output.validate().map_err(anyhow::Error::new)?;
    let artboard = output.artboard();
    let mut svg = String::new();
    writeln!(
        svg,
        r#"<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" width="{}" height="{}" viewBox="0 0 {} {}" style="isolation:isolate">"#,
        artboard.width, artboard.height, artboard.width, artboard.height
    )?;
    writeln!(svg, "  <title>Toniator — {}</title>", xml_escape(title))?;
    writeln!(
        svg,
        "  <desc>Editable canonical pattern geometry generated by Toniator</desc>"
    )?;
    writeln!(
        svg,
        "  <defs><clipPath id=\"toniator-artboard-clip\"><rect x=\"0\" y=\"0\" width=\"{}\" height=\"{}\"/></clipPath>",
        artboard.width, artboard.height
    )?;
    match output {
        CanonicalPatternOutput::Regions(output) => write_region_svg(&mut svg, output, "", token)?,
        CanonicalPatternOutput::Network(output) => write_network_svg(&mut svg, output, "", token)?,
        CanonicalPatternOutput::Composite(output) => {
            if let Some(regions) = &output.regions {
                write_region_svg(&mut svg, regions, "regions-", token)?;
            }
            if let Some(network) = &output.network {
                write_network_svg(&mut svg, network, "network-", token)?;
            }
        }
        CanonicalPatternOutput::Marks(_) | CanonicalPatternOutput::Paths(_) => {
            // Marks and paths retain their established document SVG forms in
            // `export_svg_cancellable`; this helper is for new algebra forms.
        }
    }
    writeln!(svg, "  </defs>")?;
    write_export_background(&mut svg, export_background)?;
    match output {
        CanonicalPatternOutput::Regions(output) => {
            write_region_layers_svg(&mut svg, output, "", token)?
        }
        CanonicalPatternOutput::Network(output) => {
            write_network_layers_svg(&mut svg, output, "", token)?
        }
        CanonicalPatternOutput::Composite(output) => {
            if let Some(regions) = &output.regions {
                write_region_layers_svg(&mut svg, regions, "regions-", token)?;
            }
            if let Some(network) = &output.network {
                write_network_layers_svg(&mut svg, network, "network-", token)?;
            }
        }
        CanonicalPatternOutput::Marks(_) | CanonicalPatternOutput::Paths(_) => {}
    }
    writeln!(svg, "</svg>")?;
    token.checkpoint()?;
    Ok(svg.into_bytes())
}

fn ordered_layers(layers: &[CanonicalLayer]) -> Vec<&CanonicalLayer> {
    let mut layers: Vec<_> = layers.iter().collect();
    layers.sort_by_key(|layer| (layer.order, layer.id));
    layers
}

fn is_model_aware_semantic_region_output(output: &RegionPatternOutput) -> bool {
    let Some(first_channel) = output.layers.first().and_then(|layer| layer.channel) else {
        return false;
    };
    let model = if first_channel.belongs_to(OutputModel::RgbScreen) {
        OutputModel::RgbScreen
    } else {
        OutputModel::CmykPrint
    };
    output.layers.iter().all(|layer| {
        layer
            .channel
            .is_some_and(|channel| channel.belongs_to(model))
    })
}

fn write_region_svg(
    svg: &mut String,
    output: &RegionPatternOutput,
    mask_prefix: &str,
    token: &CancellationToken,
) -> std::fmt::Result {
    for layer in ordered_layers(&output.layers) {
        token.checkpoint().map_err(|_| std::fmt::Error)?;
        let negatives: Vec<_> = output
            .regions
            .iter()
            .filter(|region| {
                region.layer_id == layer.id && region.polarity == GeometryPolarity::Subtractive
            })
            .collect();
        if negatives.is_empty() {
            continue;
        }
        writeln!(
            svg,
            "    <mask id=\"toniator-{}layer-{}-subtract\" maskUnits=\"userSpaceOnUse\" x=\"0\" y=\"0\" width=\"{}\" height=\"{}\"><rect x=\"0\" y=\"0\" width=\"100%\" height=\"100%\" fill=\"white\"/>",
            mask_prefix, layer.id.0, output.artboard.width, output.artboard.height
        )?;
        for region in negatives {
            token.checkpoint().map_err(|_| std::fmt::Error)?;
            writeln!(
                svg,
                "      <path d=\"{}\" fill=\"black\" fill-rule=\"{}\"{} />",
                region_path_data(region),
                svg_fill_rule(region.fill_rule),
                svg_transform(region.transform)
            )?;
        }
        writeln!(svg, "    </mask>")?;
    }
    Ok(())
}

fn write_region_layers_svg(
    svg: &mut String,
    output: &RegionPatternOutput,
    mask_prefix: &str,
    token: &CancellationToken,
) -> std::fmt::Result {
    let compound_semantic_regions = is_model_aware_semantic_region_output(output);
    for layer in ordered_layers(&output.layers) {
        token.checkpoint().map_err(|_| std::fmt::Error)?;
        let has_subtraction = output.regions.iter().any(|region| {
            region.layer_id == layer.id && region.polarity == GeometryPolarity::Subtractive
        });
        writeln!(
            svg,
            "  <g id=\"toniator-{}layer-{}\" inkscape:groupmode=\"layer\" inkscape:label=\"{}\" fill=\"#{:02x}{:02x}{:02x}\" opacity=\"{}\" style=\"mix-blend-mode:{}\" clip-path=\"url(#toniator-artboard-clip)\"{}>",
            mask_prefix,
            layer.id.0,
            xml_escape(&layer.label),
            layer.color.red,
            layer.color.green,
            layer.color.blue,
            number(layer.opacity),
            svg_blend_mode(layer.blend_mode),
            if has_subtraction {
                format!(
                    " mask=\"url(#toniator-{}layer-{}-subtract)\"",
                    mask_prefix, layer.id.0
                )
            } else {
                String::new()
            }
        )?;
        let mut regions: Vec<_> = output
            .regions
            .iter()
            .filter(|region| {
                region.layer_id == layer.id && region.polarity == GeometryPolarity::Positive
            })
            .collect();
        regions.sort_by_key(|region| (region.order, region.id));
        if compound_semantic_regions
            && let Some(first) = regions.first()
            && regions.iter().all(|region| {
                region.fill_rule == first.fill_rule && region.transform == first.transform
            })
        {
            // The artboard clip remains an explicit page/domain boundary for
            // valid out-of-bounds canonical geometry. This compound path is
            // the final visible cell geometry; no clipping mask is needed.
            for _ in &regions {
                token.checkpoint().map_err(|_| std::fmt::Error)?;
            }
            writeln!(
                svg,
                "    <path id=\"toniator-{}layer-{}-regions\" d=\"{}\" fill-rule=\"{}\"{} />",
                mask_prefix,
                layer.id.0,
                compound_region_path_data(&regions),
                svg_fill_rule(first.fill_rule),
                svg_transform(first.transform)
            )?;
        } else {
            for region in regions {
                token.checkpoint().map_err(|_| std::fmt::Error)?;
                writeln!(
                    svg,
                    "    <path id=\"toniator-{}layer-{}-region-{}\" d=\"{}\" fill-rule=\"{}\"{} />",
                    mask_prefix,
                    layer.id.0,
                    region.id.0,
                    region_path_data(region),
                    svg_fill_rule(region.fill_rule),
                    svg_transform(region.transform)
                )?;
            }
        }
        writeln!(svg, "  </g>")?;
    }
    Ok(())
}

fn compound_region_path_data(regions: &[&crate::pattern::FilledRegion]) -> String {
    regions
        .iter()
        .map(|region| region_path_data(region))
        .collect::<Vec<_>>()
        .join(" ")
}

fn write_network_svg(
    svg: &mut String,
    output: &NetworkPatternOutput,
    mask_prefix: &str,
    token: &CancellationToken,
) -> std::fmt::Result {
    for layer in ordered_layers(&output.layers) {
        token.checkpoint().map_err(|_| std::fmt::Error)?;
        let negative_edges: Vec<_> = output
            .edges
            .iter()
            .filter(|edge| {
                edge.layer_id == layer.id && edge.polarity == GeometryPolarity::Subtractive
            })
            .collect();
        let negative_strokes: Vec<_> = output
            .strokes
            .iter()
            .filter(|stroke| {
                stroke.layer_id == layer.id && stroke.polarity == GeometryPolarity::Subtractive
            })
            .collect();
        if negative_edges.is_empty() && negative_strokes.is_empty() {
            continue;
        }
        writeln!(
            svg,
            "    <mask id=\"toniator-{}layer-{}-subtract\" maskUnits=\"userSpaceOnUse\" x=\"0\" y=\"0\" width=\"{}\" height=\"{}\"><rect x=\"0\" y=\"0\" width=\"100%\" height=\"100%\" fill=\"white\"/>",
            mask_prefix, layer.id.0, output.artboard.width, output.artboard.height
        )?;
        for edge in negative_edges {
            token.checkpoint().map_err(|_| std::fmt::Error)?;
            writeln!(
                svg,
                "      <path d=\"{}\" fill=\"none\" stroke=\"black\" stroke-width=\"{}\"{} />",
                network_edge_path_data(output, edge.start, edge.end),
                number(edge.width),
                svg_transform(output.transform)
            )?;
        }
        for stroke in negative_strokes {
            token.checkpoint().map_err(|_| std::fmt::Error)?;
            writeln!(
                svg,
                "      <path d=\"{}\" fill=\"black\" stroke=\"none\"{} />",
                stroke.outline.to_svg_path_data(),
                svg_transform(output.transform)
            )?;
        }
        writeln!(svg, "    </mask>")?;
    }
    Ok(())
}

fn write_network_layers_svg(
    svg: &mut String,
    output: &NetworkPatternOutput,
    mask_prefix: &str,
    token: &CancellationToken,
) -> std::fmt::Result {
    for layer in ordered_layers(&output.layers) {
        token.checkpoint().map_err(|_| std::fmt::Error)?;
        let has_subtraction = output.edges.iter().any(|edge| {
            edge.layer_id == layer.id && edge.polarity == GeometryPolarity::Subtractive
        }) || output.strokes.iter().any(|stroke| {
            stroke.layer_id == layer.id && stroke.polarity == GeometryPolarity::Subtractive
        });
        let has_strokes = output
            .strokes
            .iter()
            .any(|stroke| stroke.layer_id == layer.id);
        writeln!(
            svg,
            "  <g id=\"toniator-{}layer-{}\" inkscape:groupmode=\"layer\" inkscape:label=\"{}\" fill=\"none\" stroke=\"#{:02x}{:02x}{:02x}\" opacity=\"{}\" style=\"mix-blend-mode:{}\" clip-path=\"url(#toniator-artboard-clip)\"{}>",
            mask_prefix,
            layer.id.0,
            xml_escape(&layer.label),
            layer.color.red,
            layer.color.green,
            layer.color.blue,
            number(layer.opacity),
            svg_blend_mode(layer.blend_mode),
            if has_subtraction {
                format!(
                    " mask=\"url(#toniator-{}layer-{}-subtract)\"",
                    mask_prefix, layer.id.0
                )
            } else {
                String::new()
            }
        )?;
        if has_strokes {
            let mut strokes: Vec<_> = output
                .strokes
                .iter()
                .filter(|stroke| {
                    stroke.layer_id == layer.id && stroke.polarity == GeometryPolarity::Positive
                })
                .collect();
            strokes.sort_by_key(|stroke| (stroke.order, stroke.id));
            for stroke in strokes {
                token.checkpoint().map_err(|_| std::fmt::Error)?;
                writeln!(
                    svg,
                    "    <path id=\"toniator-{}layer-{}-stroke-{}\" d=\"{}\" fill=\"#{:02x}{:02x}{:02x}\" stroke=\"none\"{} />",
                    mask_prefix,
                    layer.id.0,
                    stroke.id.0,
                    stroke.outline.to_svg_path_data(),
                    layer.color.red,
                    layer.color.green,
                    layer.color.blue,
                    svg_transform(output.transform)
                )?;
            }
        } else {
            let mut edges: Vec<_> = output
                .edges
                .iter()
                .filter(|edge| {
                    edge.layer_id == layer.id && edge.polarity == GeometryPolarity::Positive
                })
                .collect();
            edges.sort_by_key(|edge| (edge.order, edge.id));
            for edge in edges {
                token.checkpoint().map_err(|_| std::fmt::Error)?;
                writeln!(
                    svg,
                    "    <path id=\"toniator-{}layer-{}-edge-{}\" d=\"{}\" stroke-width=\"{}\"{} />",
                    mask_prefix,
                    layer.id.0,
                    edge.id.0,
                    network_edge_path_data(output, edge.start, edge.end),
                    number(edge.width),
                    svg_transform(output.transform)
                )?;
            }
        }
        writeln!(svg, "  </g>")?;
    }
    Ok(())
}

fn region_path_data(region: &crate::pattern::FilledRegion) -> String {
    let mut path = String::new();
    for ring in &region.rings {
        if !path.is_empty() {
            path.push(' ');
        }
        let first = ring.vertices[0];
        path.push_str(&format!("M {} {}", number(first.x), number(first.y)));
        for point in &ring.vertices[1..] {
            path.push_str(&format!(" L {} {}", number(point.x), number(point.y)));
        }
        path.push_str(" Z");
    }
    path
}

